function rects(rows: string[]) {
  const out: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === "#") {
        let w = 1;
        while (row[x + w] === "#") w++;
        out.push({ x, y, w });
        x += w;
      } else x++;
    }
  });
  return out;
}

const cache = new Map<string, { x: number; y: number; w: number }[]>();

export type IconName = keyof typeof art;

export function Icon({ name, size = 18, label }: { name: IconName; size?: number; label?: string }) {
  let r = cache.get(name);
  if (!r) {
    r = rects(art[name]);
    cache.set(name, r);
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      style={{ flex: "none" }}
    >
      {r.map((p, i) => (
        <rect key={i} x={p.x} y={p.y} width={p.w} height={1} />
      ))}
    </svg>
  );
}
